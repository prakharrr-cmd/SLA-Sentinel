import React, { useState } from 'react';

export default function ExplainabilityView({ tickets, teams, onReassign }) {
  const [activeTicketId, setActiveTicketId] = useState(tickets[0]?.id || 'T101');
  const activeTicket = tickets.find(t => t.id === activeTicketId) || tickets[0];
  const targetTeam = teams.find(t => t.id === activeTicket?.recommendedTeamId) || teams.find(t => t.id === 'team-b');

  return (
    <div className="space-y-6">
      
      {/* Header */}
      <div className="pb-4 border-b border-[#E2EAE5]">
        <div className="flex items-center space-x-2">
          <span className="text-[10px] font-bold font-mono px-2 py-0.5 bg-[#DCE9E1]/70 border border-[#145C43]/20 text-[#145C43] rounded-md">
            PILLAR 4 • DELIVERABLE 3
          </span>
          <span className="text-xs text-[#667873]">Explainable Decision Engine</span>
        </div>
        <h2 className="text-xl font-bold tracking-tight text-[#172B28] mt-1">
          Evidence-Based Decision Inspector
        </h2>
        <p className="text-xs text-[#667873] mt-1 max-w-3xl">
          Every recommendation generated by the engine includes transparent reasoning, multi-point evidence, and quantifiable impact estimates to ensure manager confidence.
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        
        {/* Ticket Selector List */}
        <div className="bg-white border border-[#E2EAE5] rounded-2xl p-4 shadow-2xs">
          <h3 className="text-xs font-bold uppercase tracking-wider text-[#667873] mb-3">
            Select Decision to Inspect
          </h3>
          <div className="space-y-2">
            {tickets.map(ticket => {
              const isSelected = ticket.id === activeTicketId;
              return (
                <button
                  key={ticket.id}
                  onClick={() => setActiveTicketId(ticket.id)}
                  className={`w-full text-left p-3 rounded-xl border text-xs transition flex items-center justify-between cursor-pointer ${
                    isSelected
                      ? 'border-[#145C43] bg-[#DCE9E1]/40 border-l-4 border-l-[#145C43] text-[#172B28] font-semibold'
                      : 'border-[#E2EAE5] bg-white hover:bg-[#F4F7F5] text-[#172B28]'
                  }`}
                >
                  <div>
                    <div className="flex items-center space-x-1.5">
                      <span className="font-mono font-bold text-[#172B28]">{ticket.id}</span>
                      <span className="text-[#667873]">• {ticket.category}</span>
                    </div>
                    <div className="font-medium text-[#172B28] line-clamp-1 mt-0.5">
                      {ticket.problem}
                    </div>
                  </div>
                  <span className={`text-[10px] font-mono font-bold px-1.5 py-0.5 rounded-md ${
                    ticket.riskScore >= 75
                      ? 'bg-rose-50 text-rose-700 border border-rose-200'
                      : 'bg-[#F4F7F5] text-[#667873] border border-[#E2EAE5]'
                  }`}>
                    {ticket.riskScore}/100
                  </span>
                </button>
              );
            })}
          </div>
        </div>

        {/* Deep Explainability Card */}
        <div className="lg:col-span-2 bg-white border border-[#E2EAE5] rounded-2xl p-6 shadow-2xs space-y-6">
          
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 pb-4 border-b border-[#E2EAE5]">
            <div>
              <div className="flex items-center space-x-2">
                <span className="font-mono text-xs font-bold px-2 py-0.5 bg-[#F4F7F5] border border-[#E2EAE5] text-[#172B28] rounded-md">
                  {activeTicket.id}
                </span>
                <span className="text-xs text-[#667873]">
                  {activeTicket.priority} Priority • {activeTicket.category}
                </span>
              </div>
              <h3 className="text-base font-bold text-[#172B28] mt-1">
                {activeTicket.problem}
              </h3>
            </div>

            <div className="text-right">
              <div className="text-[10px] uppercase font-bold text-[#667873]">AI Recommendation</div>
              <div className="text-xs font-bold text-[#145C43]">{activeTicket.suggestedAction}</div>
            </div>
          </div>

          {/* Evidence Chain */}
          <div>
            <h4 className="text-xs font-bold text-[#172B28] uppercase tracking-wider mb-3">
              Evidence Chain (Why this was flagged)
            </h4>
            <div className="space-y-2">
              {(activeTicket.evidence || [activeTicket.flagReason]).map((item, i) => (
                <div
                  key={i}
                  className="p-3 bg-[#F4F7F5] border border-[#E2EAE5] rounded-xl flex items-start space-x-2.5 text-xs text-[#172B28]"
                >
                  <span className="font-mono font-bold text-[#145C43] mt-0.5">
                    0{i + 1}.
                  </span>
                  <span className="leading-relaxed text-[#172B28]">{item}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Quantifiable Impact & Algorithm Attribution */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div className="p-4 bg-[#F4F7F5] border border-[#E2EAE5] rounded-xl">
              <div className="text-[10px] font-bold uppercase tracking-wider text-[#667873]">
                Estimated Impact of Action
              </div>
              <div className="text-xs font-bold text-[#172B28] mt-1">
                {activeTicket.impactEstimate || 'Prevents projected SLA violation'}
              </div>
              <p className="text-[11px] text-[#667873] mt-1">
                Quantified against category MTTR benchmarks
              </p>
            </div>

            <div className="p-4 bg-[#F4F7F5] border border-[#E2EAE5] rounded-xl">
              <div className="text-[10px] font-bold uppercase tracking-wider text-[#667873]">
                Confidence &amp; Model Provenance
              </div>
              <div className="text-xs font-bold text-[#172B28] mt-1">
                94% Model Confidence
              </div>
              <p className="text-[11px] text-[#667873] mt-1">
                Rule-based heuristic + Random Forest Classifier
              </p>
            </div>
          </div>

          {/* Quick Action Button */}
          {activeTicket.actionType === 'Reassign' && targetTeam && (
            <div className="pt-2 flex justify-end">
              <button
                onClick={() => onReassign(activeTicket.id, targetTeam.id)}
                className="px-5 py-2.5 text-xs font-bold rounded-xl bg-[#145C43] hover:bg-[#103D30] text-white shadow-2xs transition cursor-pointer"
              >
                Approve Transfer to {targetTeam.name.split('-')[0]}
              </button>
            </div>
          )}

        </div>

      </div>

    </div>
  );
}
